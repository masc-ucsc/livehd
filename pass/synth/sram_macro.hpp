namespace livehd::synth {

// synth.sram: an inferred memory kept native (see build_memory_modules) becomes a generated SRAM
// macro instead of a `cgen_memory_*` RTL instance, whatever its port count: the module that
// enclosed the memory is replaced by a body-less cell with the same pins, and a Liberty and a LEF
// view of it are generated for the timers and the placer, exactly as for an explicit fakeram cell.
//
// The macro is the memory, not a model of it: reads are combinational from the address when the
// memory's read port is asynchronous (the registered output the source puts after it stays a
// flop) and clocked when the port is synchronous; a write lands on the clock edge, per `wensize`
// lane. Same-edge write/write and write/read collisions are the macro's contract, as for every
// SRAM macro, so a memory whose forwarding matrix is not all zero stays native.
//
// The physical model is analytic, in the manner of bsg_fakeram: constant access/setup/hold
// times, area proportional to the bits and to the port count, pins spread over the four edges.
// Every number is an option (`synth.sram.*`); the defaults are asap7's.
struct Sram_tech {
  double um2_per_bit    = 0.49;    // macro area per stored bit (fakeram_asap7 as generated by HighTide)
  double port_growth    = 0.25;    // extra area per port beyond two, as a fraction
  double aspect         = 1.5;     // height / width the macro aims for
  double min_dim_um     = 6.221;
  double snap_w_um      = 0.19;
  double snap_h_um      = 1.4;
  double lr_pitch_um    = 0.048;   // pin pitch on the left/right edges
  double tb_pitch_um    = 0.036;
  double lr_len_um      = 0.072;
  double lr_width_um    = 0.024;
  double tb_len_um      = 0.054;
  double tb_width_um    = 0.018;
  std::string lr_layer     = "M4";
  std::string tb_layer     = "M3";
  std::string supply_layer = "M4";
  double supply_width_um   = 0.096;
  double supply_pitch_um   = 0.768;
  double clk_to_q_ns    = 0.218;   // a clocked read; also an address-to-data delay for an asynchronous one
  double setup_ns       = 0.05;
  double hold_ns        = 0.05;
  double min_period_ns  = 0.157;
  double pin_cap_pf     = 0.005;
  double clk_cap_pf     = 0.025;
  double voltage        = 0.7;
  uint64_t min_bits     = 0;       // a memory with fewer bits stays for the caller (flops or native)
};

// Why no generated macro can realize `mem` (forwarding between ports, power-on contents, a
// whole-array update/reset or read, a loader image, an unknown size), or empty when one can.
[[nodiscard]] std::string sram_macro_refusal(const hhds::Node_class& mem);

struct Sram_macro {
  std::string name;
  uint64_t    bits = 0, size = 0;
  int         read_ports = 0, write_ports = 0;
  double      width_um = 0, height_um = 0;
};

struct Sram_result {
  std::vector<Sram_macro>                        macros;
  std::vector<std::pair<std::string, std::string>> kept;  // module, why it stayed a native instance
  std::vector<std::pair<std::string, std::string>> liberties;  // macro name, its library group (one file each: OpenSTA reads one library per file)
  std::string                                    lef;
};

// Convert every native memory module (attrs::memory_module) in `graphs` and drop its body.
// The caller owns writing result.liberty / result.lef and handing them to the timers and the placer.
[[nodiscard]] Sram_result macro_memories(const std::vector<std::shared_ptr<hhds::Graph>>& graphs, const Sram_tech& tech);

}  // namespace livehd::synth
