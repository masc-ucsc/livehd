#!/usr/bin/env python3
"""make_tv_sim.py -- a trace driver for translation validation's route, for one certificate.

Routes ir and vc (cert_trace) take any certificate; translation validation's step is generated
for one: `reify_design_chunked` (formal/lean/LeanSemanticPrimitives/Compiler/ReifyGen.lean) runs
`compileDesign` on the certificate while the driver is compiled and emits the step as
straight-line Lean code. This script writes that driver as one Lean file, beside a copy of the
certificate:

    <out>/<Name>TvSim.lean   the certificate (read at build time from <Name>.dcert), its reified
                             step, and a main that is HDLProof.Run.traceMain: cert_trace's
                             arguments, STEP lines and lhdcert-ckpt v1 checkpoints
    <out>/<Name>.dcert       the certificate

Build it with formal/lean/Futamura_Projection_Scripts/build-opt.sh, with the reifier added:

    EXTRA_MODULES=Compiler/ReifyGen OPT=-O2 ROOT=<abs dir> bash build-opt.sh <out>/<Name>TvSim.lean

(--build ROOT does that). The binary <ROOT>/nat/<Name>TvSim then runs

    <bin> <cycles> <stim> [edges:all|edges:third|edges:file:<path>] [init:reset|init:zero]
          [ckpt-in:<file>] [ckpt-at:<cycle>:<file>] [ckpt-out:<file>] [compact:<cycles>]

and its lines and checkpoints compare with cert_trace's byte for byte. The reified step is
proved equal to `interpretDesign` per design by `prove_reified_chunked` (`prove_reified` for
--reifier plain; Compiler/ReifyProof, on the
Mathlib side), which this driver does not run.

usage: make_tv_sim.py <cert.dcert> --out DIR [--name NAME] [--chunk N] [--reifier chunked|plain]
                      [--build ROOT] [--opt -O2]
"""
import argparse, os, re, shutil, subprocess, sys
from pathlib import Path

LIVEHD = Path(__file__).resolve().parents[4]
BUILD_OPT = LIVEHD / "formal/lean/Futamura_Projection_Scripts/build-opt.sh"


def ident(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9]", "_", s)
    return s if s[:1].isalpha() else "D" + s


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cert")
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", default="")
    ap.add_argument("--chunk", type=int, default=32, help="reify_design_chunked's chunk size")
    ap.add_argument("--reifier", default="chunked", choices=("chunked", "plain"))
    ap.add_argument("--build", default="", help="ROOT: build the driver there with build-opt.sh")
    ap.add_argument("--opt", default="-O2")
    a = ap.parse_args()
    cert = Path(a.cert)
    if not cert.is_file():
        print(f"{cert}: no such certificate", file=sys.stderr)
        return 2
    name = ident(a.name or cert.stem)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    dst = out / f"{name}.dcert"
    if not dst.exists() or dst.read_bytes() != cert.read_bytes():
        shutil.copyfile(cert, dst)
    reify = (f"reify_design_chunked cert as tvStep size {a.chunk}" if a.reifier == "chunked"
             else "reify_design cert as tvStep")
    src = out / f"{name}TvSim.lean"
    text = f"""/- Generated by pass/lean/tools/scripts/make_tv_sim.py from {cert.name}. Do not edit.
Translation validation's route for this certificate: its step reified by `{reify.split()[0]}`
(compileDesign run while this file is compiled), driven by `HDLProof.Run.traceMain`
(cert_trace's arguments, STEP lines and lhdcert-ckpt v1 checkpoints). -/
import LeanSemanticPrimitives.Compiler.CertIORoute
import LeanSemanticPrimitives.Compiler.ReifyGen
import HDLProof.Run.Trace

open Compiler

namespace TvSim.{name}

-- a big literal: closed-term extraction is most of the load time and changes nothing
set_option compiler.extract_closed false in
def certText : String := include_str "{name}.dcert"

set_option compiler.extract_closed false in
def cert : DesignCert :=
  match CertIO.admitAny certText.toUTF8 with
  | .ok (_, D) => D
  | .error _ => default

-- `admitAny` refuses with an error, read here as `default`: rule that out
#guard cert.nodes.size > 0

set_option maxRecDepth 1000000
set_option maxHeartbeats 0

{reify}

end TvSim.{name}

def main (args : List String) : IO UInt32 :=
  HDLProof.Run.traceMain "tv" TvSim.{name}.cert TvSim.{name}.tvStep args
"""
    if not src.exists() or src.read_text() != text:
        src.write_text(text)
    print(f"make_tv_sim: wrote {src}")
    if a.build:
        env = dict(os.environ, EXTRA_MODULES="Compiler/ReifyGen", OPT=a.opt, ROOT=str(Path(a.build).resolve()))
        r = subprocess.run(["bash", str(BUILD_OPT), str(src.resolve())], cwd=BUILD_OPT.parent.parent, env=env)
        if r.returncode != 0:
            print("make_tv_sim: build failed", file=sys.stderr)
            return 1
        print(f"make_tv_sim: built {Path(a.build).resolve() / 'nat' / src.stem}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
