#!/usr/bin/env python3
"""Rebuild the small, reviewable Pyrope fixtures and invented physical technology."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CASES = [
    dict(name="mesh_2x2", side=2, depth=28, pattern="mesh", target=12000),
    dict(name="mesh_4x4", side=4, depth=24, pattern="mesh", target=40000),
    dict(name="ring_32", side=9, depth=24, pattern="serpentine", target=80000,
         fixed_macros=[0, 7, 24, 31]),
    dict(name="hierarchy_4x4", side=4, depth=32, pattern="hierarchy", target=54000),
    dict(name="mesh_6x6", side=6, depth=24, pattern="mesh", target=90000),
]


def topology(case):
    if case["pattern"] == "serpentine":
        # Four horizontal runs, eight macro sites each. Only consecutive
        # sites communicate: physical proximity must not introduce mesh links.
        points = [(x, 6-2*row) for row in range(4)
                  for x in (range(1, 9) if row % 2 == 0 else range(8, 0, -1))]
        edges = sorted([[i, i+1] for i in range(len(points)-1)] + [[0, len(points)-1]])
        return points, edges
    n = case["side"]
    points = [(x, y) for y in range(n) for x in range(n)]
    edges = []
    for i, (x, y) in enumerate(points):
        for j in range(i+1, len(points)):
            xj, yj = points[j]
            adjacent = (x == xj and (y ^ yj) in (1, 2)) or (y == yj and (x ^ xj) in (1, 2))
            if (case["pattern"] == "hierarchy" and adjacent) or (case["pattern"] != "hierarchy" and abs(x-xj) + abs(y-yj) == 1):
                edges.append([i, j])
    return points, edges


def anchor_floorplan(case):
    """Four fixed outer corners; every unlisted macro/cell stays movable."""
    points, _ = topology(case)
    lines = ['VERSION 5.8 ;', 'DIVIDERCHAR "/" ;', 'BUSBITCHARS "[]" ;',
             f'DESIGN {case["name"]}.top ;', 'UNITS DISTANCE MICRONS 1000 ;',
             'DIEAREA ( 0 0 ) ( 1200000 960000 ) ;']
    for row in range(480):
        orientation = 'FS' if row % 2 else 'N'
        lines.append(f'ROW ROW_{row} unit 0 {row*2000} {orientation} DO 1200 BY 1 STEP 1000 0 ;')
    lines.append(f'COMPONENTS {len(case["fixed_macros"])} ;')
    for i in case["fixed_macros"]:
        x, y = points[i]
        lines.append(f'- t{i}.macro REG_MACRO + FIXED ( {(80+120*x)*1000} {(80+120*y)*1000} ) N ;')
    lines += ['END COMPONENTS', 'END DESIGN']
    return '\n'.join(lines) + '\n'


def source(case):
    points, edges = topology(case)
    depth = case["depth"]
    # Distinct state per tile and nonlinear, bit-mixing cones prevent constant
    # folding or merging identical lanes. All state is observable at the top.
    lines = ["// Generated by generate.py; edit the generator, then refresh.",
             'const hard = import("lg:REG_MACRO")',
             "", "mod tile::[timecheck=false](a:U32, b:U32, salt:U32) -> (q:U32@[0]) {",
             "  reg state:U32 = nil", "  mut x:U32 = a ^ salt"]
    for layer in range(depth):
        lines += [f"  const r{layer}:U32 = ((x << 5) | (x >> 27))#[0..<32]",
                  f"  x = r{layer} ^ (x & b) ^ salt"]
    lines += ["  state = x", "  q = hard::[name=macro](D=state)", "}", ""]
    if case["pattern"] == "hierarchy":
        # Repeated quadrants add a genuine second hierarchy level. Each tile
        # has two internal and two external neighbors; quadrants form a mesh.
        lines += ["mod quadrant::[timecheck=false](west:U128, east:U128, salt:U32) -> (q:U128@[0]) {"]
        for i in range(4):
            lines.append(f"  wire w{i}:U32 = nil")
        for i in range(4):
            lines += [f"  w{i} = tile::[name=t{i}](a=w{i ^ 1} ^ west#[{32*i}..<{32*(i+1)}], "
                      f"b=w{i ^ 2} ^ east#[{32*i}..<{32*(i+1)}], salt=salt)"]
        lines += ["  q = (w3, w2, w1, w0)#[..]", "}", "",
                  'pub mod top::[timecheck=false](salt:U32) -> (q:U512@[0]) {']
        for i in range(4):
            lines.append(f"  wire w{i}:U128 = nil")
        for i in range(4):
            lines.append(f"  w{i} = quadrant::[name=g{i}](west=w{i ^ 1}, east=w{i ^ 2}, salt=salt ^ {i+1})")
        lines += ["  q = (w3, w2, w1, w0)#[..]", "}"]
    else:
        lines += [f'pub mod top::[timecheck=false](salt:U32) -> (q:U{32*len(points)}@[0]) {{']
        for i in range(len(points)):
            lines.append(f"  wire w{i}:U32 = nil")
        for i in range(len(points)):
            adjacent = [b if a == i else a for a, b in edges if i in (a, b)]
            a = " ^ ".join(f"w{j}" for j in adjacent[::2])
            b = " ^ ".join(f"w{j}" for j in adjacent[1::2])
            lines.append(f"  w{i} = tile::[name=t{i}](a={a}, b={b}, salt=salt ^ {i+1})")
        lines += ["  q = (" + ", ".join(f"w{i}" for i in reversed(range(len(points)))) + ")#[..]", "}"]
    return "\n".join(lines) + "\n"


def timing(pin, delay="0.05", kind="combinational"):
    return f'''timing() {{ related_pin : "{pin}"; timing_type : {kind};
      cell_rise(scalar) {{ values("{delay}"); }} cell_fall(scalar) {{ values("{delay}"); }}
      rise_transition(scalar) {{ values("0.02"); }} fall_transition(scalar) {{ values("0.02"); }} }}'''


def technology():
    cells = [("INV", "!A", 1), ("BUF", "A", 1), ("NAND2", "!(A & B)", 2),
             ("NOR2", "!(A | B)", 2), ("XOR2", "A ^ B", 3),
             ("TIE0", "0", 1), ("TIE1", "1", 1), ("DFF", "IQ", 4)]
    lib = ['''/* Invented educational technology. No foundry characterization. */
library(regularity) {
  delay_model : table_lookup; time_unit : "1ns"; voltage_unit : "1V";
  current_unit : "1mA"; pulling_resistance_unit : "1kohm";
  capacitive_load_unit(1,pf);
  default_input_pin_cap : 0.001; default_output_pin_cap : 0;
  default_inout_pin_cap : 0; default_fanout_load : 1;
  default_max_transition : 10;
''']
    lef = ['''# Invented units: 1um site, 2um row, 1000 DBU/um.
VERSION 5.8 ;
BUSBITCHARS "[]" ;
DIVIDERCHAR "/" ;
UNITS
 DATABASE MICRONS 1000 ;
END UNITS
MANUFACTURINGGRID 0.001 ;
SITE unit
 CLASS CORE ;
 SIZE 1 BY 2 ;
 SYMMETRY Y ;
END unit
LAYER M1
 TYPE ROUTING ; DIRECTION HORIZONTAL ; PITCH 1 ; OFFSET 0 ; WIDTH 0.2 ; SPACING 0.2 ;
 RESISTANCE RPERSQ 0.01 ; CAPACITANCE CPERSQDIST 0.0001 ; EDGECAPACITANCE 0.00001 ;
END M1
LAYER M2
 TYPE ROUTING ; DIRECTION VERTICAL ; PITCH 1 ; OFFSET 0 ; WIDTH 0.2 ; SPACING 0.2 ;
 RESISTANCE RPERSQ 0.01 ; CAPACITANCE CPERSQDIST 0.0001 ; EDGECAPACITANCE 0.00001 ;
END M2
''']

    def geometry(name, pins, width, height, macro=False):
        out = [f"MACRO {name}\n CLASS {'BLOCK' if macro else 'CORE'} ;\n ORIGIN 0 0 ;\n SIZE {width} BY {height} ;\n SYMMETRY X Y ;"]
        if not macro:
            out.append(" SITE unit ;")
        for i, (pin, direction) in enumerate(pins):
            x = (width-1 if direction == "output" else 1) if macro else (width-0.1 if direction == "output" else 0.1)
            y = i//2+1 if macro else 1
            out.append(f" PIN {pin}\n  DIRECTION {direction.upper()} ;\n  USE SIGNAL ;\n  PORT\n   LAYER M2 ;\n   RECT {x-0.05:.3f} {y-0.05:.3f} {x+0.05:.3f} {y+0.05:.3f} ;\n  END\n END {pin}")
        return "\n".join(out) + f"\nEND {name}\n"

    for name, function, width in cells:
        pins = [] if name.startswith("TIE") else [("A", "input")]
        if "2" in name:
            pins.append(("B", "input"))
        if name == "DFF":
            pins = [("D", "input"), ("CLK", "input")]
        pins.append(("Q" if name == "DFF" else "Y", "output"))
        lib.append(f"cell({name}) {{ area : {2*width};")
        if name == "DFF":
            lib.append('ff(IQ,IQN) { next_state : "D"; clocked_on : "CLK"; }')
        for pin, direction in pins:
            lib.append(f"pin({pin}) {{ direction : {direction};")
            if direction == "input":
                lib.append('capacitance : 0.001;')
                if pin == "CLK":
                    lib.append("clock : true;")
                if pin == "D":
                    for kind in ("setup_rising", "hold_rising"):
                        lib.append(f'''timing() {{ related_pin : "CLK"; timing_type : {kind};
                          rise_constraint(scalar) {{ values("0.02"); }} fall_constraint(scalar) {{ values("0.02"); }} }}''')
            else:
                lib.append(f'function : "{function}"; max_capacitance : 10;')
                if name == "DFF":
                    lib.append(timing("CLK", kind="rising_edge"))
                else:
                    for source_pin, source_direction in pins:
                        if source_direction == "input":
                            lib.append(timing(source_pin))
            lib.append("}")
        lib.append("}")
        lef.append(geometry(name, pins, width, 2))
    # A 32-lane feed-through hard macro, not a RAM proxy. Its boundary remains
    # opaque to mapping; the 0.4ns arcs are real timed paths in the fake model.
    lib.append("cell(REG_MACRO) { area : 1600; dont_use : true;")
    pins = []
    for i in range(32):
        lib.append(f'pin("D[{i}]") {{ direction : input; capacitance : 0.005; }}')
        lib.append(f'pin("Q[{i}]") {{ direction : output; function : "D[{i}]"; max_capacitance : 10; {timing(f"D[{i}]", "0.4")} }}')
        pins += [(f"D[{i}]", "input"), (f"Q[{i}]", "output")]
    lib += ["}", "}"]
    lef.append(geometry("REG_MACRO", pins, 40, 40, True))
    lef.append("END LIBRARY\n")
    return "\n".join(lib), "\n".join(lef)


def main():
    for case in CASES:
        (ROOT / (case["name"] + ".prp")).write_text(source(case))
        if case.get("fixed_macros"):
            (ROOT / (case["name"] + ".def")).write_text(anchor_floorplan(case))
    lib, lef = technology()
    (ROOT / "fake.lib").write_text(lib)
    (ROOT / "fake.lef").write_text(lef)
    (ROOT / "macros.v").write_text('(* blackbox *) module REG_MACRO(input [31:0] D, output [31:0] Q); endmodule\n')
    (ROOT / "timing.sdc").write_text('create_clock -name clock -period 20 [get_ports clock]\n'
                                      'set_input_delay -clock clock 0.1 [all_inputs]\n'
                                      'set_output_delay -clock clock 0.1 [all_outputs]\n')
    (ROOT / "benchmarks.json").write_text(json.dumps(CASES, indent=2) + "\n")


if __name__ == "__main__":
    main()
